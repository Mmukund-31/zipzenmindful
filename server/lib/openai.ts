// This module used to call the Gemini API directly. All AI logic (RAG pipelines, a LangChain
// tool-calling agent, Chroma vector-backed memory, multilingual prompting) now lives in the
// Python/FastAPI "ai-service" microservice (see /ai-service). This file is a thin HTTP adapter
// that preserves the exact function names/signatures/return shapes the rest of the app already
// depends on, so routes.ts and the client are unaffected by the swap.

const AI_SERVICE_URL = process.env.AI_SERVICE_URL || "http://localhost:8000";
const REQUEST_TIMEOUT_MS = 30_000;

async function callAiService<T>(path: string, body?: unknown, init?: RequestInit): Promise<T> {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

  try {
    const response = await fetch(`${AI_SERVICE_URL}${path}`, {
      method: "POST",
      headers: body !== undefined ? { "Content-Type": "application/json" } : undefined,
      body: body !== undefined ? JSON.stringify(body) : undefined,
      signal: controller.signal,
      ...init,
    });

    if (!response.ok) {
      throw new Error(`ai-service ${path} responded with ${response.status}`);
    }

    return (await response.json()) as T;
  } finally {
    clearTimeout(timeout);
  }
}

export async function analyzeImageAndGenerateMeme(imageBuffer: Buffer, style: string): Promise<{
  topText: string;
  bottomText: string;
  description: string;
}> {
  try {
    const form = new FormData();
    form.append("style", style);
    form.append("image", new Blob([imageBuffer]), "image.jpg");

    const result = await callAiService<{ top_text: string; bottom_text: string; description: string }>(
      "/ai/meme/analyze-and-generate",
      undefined,
      { body: form }
    );

    return {
      topText: result.top_text,
      bottomText: result.bottom_text,
      description: result.description,
    };
  } catch (error) {
    console.error("ai-service meme analysis error:", error);
    return {
      topText: "AI MEME GENERATOR",
      bottomText: "MAKING EVERYTHING FUNNY",
      description: "Image analysis unavailable",
    };
  }
}

// Multilingual, RAG-grounded, tool-using chat response, generated by the LangChain agent in
// ai-service (semantic search over the wellness knowledge base, long-term per-user vector
// memory, and short-term conversational memory).
export async function generateAIResponse(
  userMessage: string,
  currentMood?: string,
  preferredLanguage?: string,
  userId?: string
): Promise<string> {
  try {
    const result = await callAiService<{ response: string }>("/ai/chat", {
      message: userMessage,
      user_id: userId,
      current_mood: currentMood,
      preferred_language: preferredLanguage,
    });
    return result.response || "I'm here to support you. Could you tell me more about how you're feeling?";
  } catch (error) {
    console.error("ai-service chat error:", error);
    return "I'm having trouble connecting right now, but I'm here for you. How can I help support your wellness today?";
  }
}

